/** The icon a machine notice or queued chip shows for its entry kind. */
export function noticeIconName(kind: string): IconName {
  const name = kind.toLowerCase().replace(/^ui[.-]/, "");
  if (name.startsWith("mcp")) return "zap";
  if (name.startsWith("job")) return "settings";
  if (name.startsWith("delegate")) return "bot";
  if (name.startsWith("idle")) return "clock";
  if (name.startsWith("task-decision")) return "check";
  if (name.startsWith("memory")) return "pen-line";
  if (name.startsWith("operator")) return "message-square";
  return "alert";
}
